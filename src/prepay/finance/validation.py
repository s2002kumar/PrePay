"""Reproducible finance-engine disclosures: rep-line error profiles and Monte Carlo convergence.

FINANCIAL_CONVENTIONS §6.9 requires the rep-line approximation error to be measured on at least
five diverse synthetic pool profiles and disclosed. ``render_report`` produces the markdown in
``docs/validation/FINANCE_ENGINE.md``; tests use the same profiles.
"""

from __future__ import annotations

import numpy as np

from prepay.finance.ledger import CreditAssumptions, HazardPaths, LoanLines, project
from prepay.finance.montecarlo import simulate
from prepay.finance.replines import RepLineError, bucket_labels, measure_error

PROFILE_MONTHS = 372
PROFILE_CREDIT = CreditAssumptions(severity=0.35, recovery_lag_months=12)
PROFILES = (
    "homogeneous",
    "coupon_dispersion",
    "mixed_terms",
    "mixed_seasoning",
    "heterogeneous_speeds",
    "credit_heavy",
)


def profile(name: str, count: int = 300) -> tuple[LoanLines, HazardPaths]:
    """Deterministic synthetic pool profile (lines + hazard paths over PROFILE_MONTHS)."""
    rng = np.random.default_rng(sum(name.encode()))
    months = PROFILE_MONTHS
    if name == "homogeneous":
        lines = LoanLines.from_values(
            np.full(count, 250_000.0), np.full(count, 0.06), np.full(count, 360)
        )
        return lines, HazardPaths.constant(count, months, 0.01, 0.0005)
    if name == "coupon_dispersion":
        rate, remaining = rng.uniform(0.025, 0.085, count), np.full(count, 360)
    elif name == "mixed_terms":
        rate, remaining = rng.uniform(0.04, 0.06, count), rng.choice([180, 360], size=count)
    elif name == "mixed_seasoning":
        rate, remaining = rng.uniform(0.03, 0.07, count), rng.integers(60, 361, count)
    elif name in ("heterogeneous_speeds", "credit_heavy"):
        rate, remaining = rng.uniform(0.05, 0.055, count), np.full(count, 360)
    else:
        raise ValueError(name)
    lines = LoanLines.from_values(rng.uniform(60_000, 900_000, count), rate, remaining)
    if name == "heterogeneous_speeds":
        speed = rng.choice([0.002, 0.04], size=count)  # fast and slow borrowers mixed
        prepay = np.repeat(speed[:, None], months, axis=1)
        credit = np.full((count, months), 0.0003)
    elif name == "credit_heavy":
        prepay = np.full((count, months), 0.006)
        credit = np.repeat(rng.uniform(0.0, 0.01, count)[:, None], months, axis=1)
    else:  # refinance incentive: higher coupons prepay faster
        prepay = np.repeat((0.002 + 0.6 * np.maximum(rate - 0.035, 0.0))[:, None], months, axis=1)
        credit = np.full((count, months), 0.0004)
    return lines, HazardPaths.from_prepay_credit(
        np.asarray(prepay, dtype=np.float64), np.asarray(credit, dtype=np.float64)
    )


def profile_error(name: str) -> RepLineError:
    lines, hazards = profile(name)
    labels = (
        np.zeros(lines.count, dtype=np.int64) if name == "homogeneous" else bucket_labels(lines)
    )
    return measure_error(lines, hazards, PROFILE_CREDIT, PROFILE_MONTHS, labels)


def monte_carlo_check(paths: int = 4000, seed: int = 20261028) -> dict[str, float]:
    lines, hazards = profile("mixed_seasoning", count=40)
    months = 48
    sub = HazardPaths.from_prepay_credit(hazards.prepay[:, :months], hazards.credit[:, :months])
    expected = project(lines, sub, PROFILE_CREDIT, months).pool
    sim = simulate(lines, sub, PROFILE_CREDIT, months, paths=paths, seed=seed)
    z = np.abs(sim.ending_upb_mean - expected.ending_upb) / np.maximum(sim.ending_upb_se, 1e-9)
    relative = np.abs(sim.ending_upb_mean - expected.ending_upb) / expected.initial_upb
    return {
        "paths": float(paths),
        "max_abs_z": float(z.max()),
        "max_relative_error": float(relative.max()),
    }


def render_report() -> str:
    rows = []
    for name in PROFILES:
        e = profile_error(name)
        wal = "n/a" if e.cash_wal_error_months is None else f"{e.cash_wal_error_months:+.2f}"
        rows.append(
            f"| {name} | {e.loan_lines} | {e.rep_lines} | "
            f"{100 * e.max_abs_ending_upb_error_fraction:.3f} | {wal} | "
            f"{e.principal_returned_12m_error_pp:+.3f} | "
            f"{e.principal_returned_24m_error_pp:+.3f} | "
            f"{100 * e.interest_accrued_error_fraction:.3f} |"
        )
    mc = monte_carlo_check()
    return "\n".join(
        [
            "<!-- GENERATED by `uv run prepay finance-report`; do not edit by hand. -->",
            "# Finance engine validation disclosures",
            "",
            "Synthetic pool profiles only (`src/prepay/finance/validation.py`); 300 loans each,",
            f"{PROFILE_MONTHS}-month full-life projection, severity 35%, recovery lag 12 months.",
            "Rep lines group loans by 25 bp note-rate bucket x 12-month remaining-term bucket",
            "(the homogeneous profile uses one line) and carry balance-weighted coupon, term and",
            "hazards (FINANCIAL_CONVENTIONS §6.9). Errors are rep-line minus exact loan-level.",
            "",
            "| Profile | Loan lines | Rep lines | Max ending-UPB error (% of initial) | "
            "Cash WAL error (months) | Returned principal 12m (pp) | Returned principal 24m (pp) | "
            "Accrued interest error (%) |",
            "|---|---:|---:|---:|---:|---:|---:|---:|",
            *rows,
            "",
            "Reading: aggregation is exact for identical loans. It is small when loans differ only",
            "in coupon or term within a bucket. It is **material when borrower speeds differ**:",
            "averaging fast and slow borrowers ignores how pool composition changes (burnout),",
            "so a single averaged line returns principal far too early. Loan-level projection is",
            "used everywhere in Prepay; rep lines are only an approximation benchmark.",
            "",
            "## Monte Carlo convergence (§6.10)",
            "",
            f"{int(mc['paths'])} seeded loan-level paths (40 loans, 48 months): max |z| of the",
            f"mean ending UPB vs the expected ledger = {mc['max_abs_z']:.2f}; max relative error",
            f"= {100 * mc['max_relative_error']:.3f}% of initial UPB. The intervals are Monte",
            "Carlo sampling intervals only, not model or parameter uncertainty.",
            "",
        ]
    )
