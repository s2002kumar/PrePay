"""Generate ``transform/macros/sflld_contract.sql`` from the Python source contract.

dbt needs the raw column lists (for duplicate-row hashing and parity tests). Generating them keeps
the contract the single source of truth; a test fails if the committed file is stale.
"""

from __future__ import annotations

from pathlib import Path

from prepay.contracts.layout import Layout
from prepay.contracts.sflld import LAYOUT_ID, ORIGINATION, PERFORMANCE

HEADER = """\
{#- GENERATED by prepay.contracts.dbt_codegen from src/prepay/contracts/sflld.py. Do not edit.
    Regenerate with: uv run python -m prepay.contracts.dbt_codegen
-#}
"""


def _macro(name: str, layout: Layout) -> str:
    columns = ", ".join(f"'{c}'" for c in layout.column_names)
    return f"{{% macro {name}() -%}}\n  {{{{ return([{columns}]) }}}}\n{{%- endmacro %}}\n"


def render() -> str:
    return (
        HEADER + f"\n{{# layout {LAYOUT_ID}: origination {ORIGINATION.fingerprint()[:16]}, "
        f"performance {PERFORMANCE.fingerprint()[:16]} #}}\n\n"
        + _macro("sflld_origination_columns", ORIGINATION)
        + "\n"
        + _macro("sflld_performance_columns", PERFORMANCE)
    )


TARGET = Path(__file__).resolve().parents[3] / "transform" / "macros" / "sflld_contract.sql"


if __name__ == "__main__":
    TARGET.write_text(render(), encoding="utf-8", newline="\n")
